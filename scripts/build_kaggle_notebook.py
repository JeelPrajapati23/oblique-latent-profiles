"""Pack the current code + prompts into self-contained Kaggle notebooks.

    python scripts/build_kaggle_notebook.py             ->  kaggle/handtest_prompts.ipynb
    python scripts/build_kaggle_notebook.py --profile   ->  kaggle/profile_corpus.ipynb

Re-run after changing any prompt or source file, then re-upload the notebook to Kaggle.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROMPT_FILES = sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / "prompts").glob("*.txt"))
FILES = ["src/obliq/__init__.py", "src/obliq/data.py", "src/obliq/runs.py", "src/obliq/profiles.py",
         "scripts/handtest_prompts.py", *PROMPT_FILES]
RUNS = [("writing", ""), ("math", ""), ("math", " --setting math_soln")]
# Full profiling: Writing first (core task), then Math, then the solution-aware Math variant
# (its queries use the same prompt as plain Math, so only its docs are needed).
PROFILE_FILES = ["src/obliq/__init__.py", "src/obliq/data.py", "src/obliq/profiles.py",
                 "scripts/profile_corpus.py", *PROMPT_FILES]
PROFILE_RUNS = [("writing", ""), ("math", ""), ("math", " --setting math_soln --kinds doc")]
# Round-2 hand-test profiles, shipped so their 20 items per setting aren't generated again.
SEED = ["writing/writing-86bf72__Qwen2.5-7B-Instruct-AWQ", "math/math-ee895b__Qwen2.5-7B-Instruct-AWQ",
        "math/math_soln-33bb08__Qwen2.5-7B-Instruct-AWQ"]


def md(text):
    return {"cell_type": "markdown", "metadata": {}, "source": text}


def code(text):
    return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [], "source": text}


def setup_cells(files):
    cells = [
        # vLLM brings its own torch build; Kaggle's preinstalled torchaudio is built for a different
        # CUDA and breaks `import transformers`. We don't need audio, so remove it.
        code("!pip install -q vllm sentence-transformers huggingface_hub\n"
             "!pip uninstall -y -q torchaudio\n"
             "import torch; print(torch.__version__, torch.cuda.device_count(), 'GPUs')"),
        code("import os\n"
             "for d in sorted({os.path.dirname(f) for f in %r}):\n"
             "    os.makedirs(f'/kaggle/working/irproj/{d}', exist_ok=True)\n"
             "%%cd /kaggle/working/irproj" % (files,)),
    ]
    for f in files:
        # %%writefile rejects an empty cell body (e.g. an empty __init__.py)
        body = (ROOT / f).read_text(encoding="utf-8") or "# package marker\n"
        cells.append(code(f"%%writefile {f}\n{body}"))
    return cells


def handtest_notebook():
    cells = [md("# Latent profiles: prompt hand-test (Week 1)\n\n"
                "**Settings (right panel):** Accelerator = **GPU T4 x2**, Internet = **On** "
                "(needs a phone-verified Kaggle account).\n\n"
                "Then *Run All*. Takes ~15-25 min, mostly installing vLLM and downloading the model. "
                "At the end, download `handtest_outputs.zip` from the Output panel and put it in the "
                "project folder.\n\nGenerated by `scripts/build_kaggle_notebook.py`; don't edit by hand.")]
    cells += setup_cells(FILES)
    cells.append(md("## Run the three hand-tests\n\nLLM on GPU 0 (vLLM), embedder on GPU 1. "
                    "Each run is a fresh process so vLLM releases GPU memory between runs."))
    for task, extra in RUNS:
        cells.append(code(f"!python scripts/handtest_prompts.py --task {task}{extra} "
                          f"--backend vllm --embed-device cuda:1"))
    cells.append(code("!zip -qr /kaggle/working/handtest_outputs.zip reports profiles\n"
                      "!ls -la /kaggle/working/handtest_outputs.zip"))
    return cells, "handtest_prompts.ipynb"


def profile_notebook():
    files = list(PROFILE_FILES)
    for v in SEED:
        files += sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / "profiles" / v).iterdir()
                        if p.suffix in (".jsonl", ".json"))
    cells = [md("# Latent profiles: profile every document and query (Week 2)\n\n"
                "**Settings:** Accelerator = **GPU T4 x2**, Internet = **On**.\n\n"
                "Use **Save Version -> Save & Run All (Commit)** so it runs in the background (up to 12 h) "
                "and the outputs are kept. When it finishes, download `profiles_out.zip` from the Output tab "
                "and unzip it in the project folder (it only adds to `profiles/`).\n\n"
                "**Resuming:** if a run stops early, add that version's output as an Input to this notebook "
                "and run again; cached profiles are copied in and skipped.\n\n"
                "One vLLM process per T4, each on half the ids. The first run is a timing pilot on the "
                "first 200 Writing docs and queries; its estimate is printed in the log.\n\n"
                "Generated by `scripts/build_kaggle_notebook.py --profile`; don't edit by hand.")]
    cells += setup_cells(files)
    cells.append(code(
        "# Resume: copy profiles from any attached Input (an earlier version's output); keep the bigger file\n"
        "import glob, os, shutil, zipfile\n"
        "for z in glob.glob('/kaggle/input/**/profiles_out.zip', recursive=True):\n"
        "    zipfile.ZipFile(z).extractall('/kaggle/tmp_resume')\n"
        "for src in glob.glob('/kaggle/input/**/profiles', recursive=True) + glob.glob('/kaggle/tmp_resume/profiles'):\n"
        "    for f in glob.glob(f'{src}/**/*', recursive=True):\n"
        "        dst = os.path.join('profiles', os.path.relpath(f, src))\n"
        "        if os.path.isfile(f) and (not os.path.exists(dst) or os.path.getsize(f) > os.path.getsize(dst)):\n"
        "            os.makedirs(os.path.dirname(dst), exist_ok=True)\n"
        "            shutil.copy(f, dst)\n"
        "            print('resumed', dst)"))
    zip_cmd = "!zip -qr /kaggle/working/profiles_out.zip profiles && ls -la /kaggle/working/profiles_out.zip"
    cells.append(md("## Timing pilot (first 200 Writing docs and queries)"))
    cells.append(code("!python scripts/profile_corpus.py --task writing --limit 200"))
    cells.append(md("## Full runs\n\nThe zip is refreshed after each run, so a later failure keeps earlier work."))
    for task, extra in PROFILE_RUNS:
        cells.append(code(f"!python scripts/profile_corpus.py --task {task}{extra}\n{zip_cmd}"))
    cells.append(code("!cat profiles/*/*/cost.jsonl"))
    return cells, "profile_corpus.ipynb"


def rerank_notebook(tasks=("math",)):
    files = ["src/obliq/__init__.py", "src/obliq/data.py", "src/obliq/runs.py", "src/obliq/profiles.py",
             "src/obliq/rerank.py", "scripts/rerank.py"]
    for t in tasks:
        files += sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / "rerank" / t).glob("input_*.json"))
        if (ROOT / "rerank" / t / "windows.jsonl").exists():  # resume: already-answered windows are skipped
            files.append(f"rerank/{t}/windows.jsonl")
    cells = [md("# E5: listwise LLM re-ranking of the top 50 (Week 3)\n\n"
                "**Settings:** Accelerator = **GPU T4 x2** (one is used), Internet = **On**. "
                "Use **Save & Run All (Commit)**. Takes ~15-25 min including the vLLM install.\n\n"
                "When done, download `rerank_out.zip` from the Output tab and unzip it in the project folder, "
                "then run `python scripts/rerank.py --task math` locally to build and save the E5 run.\n\n"
                "Generated by `scripts/build_kaggle_notebook.py --rerank`; don't edit by hand.")]
    cells += setup_cells(files)
    for t in tasks:
        cells.append(code(f"!python scripts/rerank.py --task {t} --llm"))
    cells.append(code("!zip -qr /kaggle/working/rerank_out.zip rerank && ls -la /kaggle/working/rerank_out.zip\n"
                      "!cat rerank/*/cost.jsonl"))
    return cells, "rerank.ipynb"


def rewrite_notebook():
    cells = [md("# E2: query rewriting with the same open LLM (Week 3)\n\n"
                "**Settings:** Accelerator = **GPU T4 x2**, Internet = **On**. Use **Save & Run All (Commit)**. "
                "Rewrites the 151 Math and 512 Writing queries once (~10 min plus the vLLM install).\n\n"
                "When done, download `rewrite_out.zip` from the Output tab and unzip it in the project folder, "
                "then run `python scripts/run_rewrite.py` locally.\n\n"
                "Generated by `scripts/build_kaggle_notebook.py --rewrite`; don't edit by hand.")]
    cells += setup_cells(PROFILE_FILES)
    for task in ["math", "writing"]:
        cells.append(code(f"!python scripts/profile_corpus.py --task {task} --setting {task}_rewrite --kinds query"))
    cells.append(code("!zip -qr /kaggle/working/rewrite_out.zip profiles && ls -la /kaggle/working/rewrite_out.zip"))
    return cells, "rewrite.ipynb"


ABLATION_RUNS = [("A1 topic words allowed", "--setting math_topic"),
                 ("A3 ~40-word profiles", "--setting math_short"),
                 ("A2 3B profiler (same prompt as the main system)", "--model Qwen/Qwen2.5-3B-Instruct-AWQ")]


def ablation_notebook():
    cells = [md("# Ablations A1-A3 on Math (Week 3)\n\n"
                "**Settings:** Accelerator = **GPU T4 x2**, Internet = **On**. Use **Save & Run All (Commit)**. "
                "Profiles all 3,639 Math docs + queries three times (main run was ~16 GPU-min; expect ~1 h "
                "wall in total including the vLLM install).\n\n"
                "When done, download `ablation_out.zip` from the Output tab, unzip it in the project folder "
                "(`unzip -n`), then run `python scripts/run_ablations.py` locally.\n\n"
                "Generated by `scripts/build_kaggle_notebook.py --ablation`; don't edit by hand.")]
    cells += setup_cells(PROFILE_FILES)
    zip_cmd = "!zip -qr /kaggle/working/ablation_out.zip profiles && ls -la /kaggle/working/ablation_out.zip"
    for title, flags in ABLATION_RUNS:
        cells.append(md(f"## {title}"))
        cells.append(code(f"!python scripts/profile_corpus.py --task math {flags}\n{zip_cmd}"))
    cells.append(code("# eyeball: the first two doc profiles of each variant\n"
                      "import glob, json\n"
                      "for f in sorted(glob.glob('profiles/math/*/docs.jsonl')):\n"
                      "    print('==', f)\n"
                      "    for line in open(f).readlines()[:2]:\n"
                      "        print(json.loads(line)['profile'], '\\n')\n"
                      "!cat profiles/*/*/cost.jsonl"))
    return cells, "ablation.ipynb"


def main():
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--profile", action="store_true", help="build the full-corpus profiling notebook")
    g.add_argument("--rerank", action="store_true", help="build the E5 re-ranking notebook")
    g.add_argument("--rewrite", action="store_true", help="build the E2 query-rewriting notebook")
    g.add_argument("--ablation", action="store_true", help="build the A1-A3 Math ablation notebook")
    args = ap.parse_args()
    cells, name = (profile_notebook() if args.profile else rerank_notebook() if args.rerank
                   else rewrite_notebook() if args.rewrite else ablation_notebook() if args.ablation
                   else handtest_notebook())
    nb = {"cells": cells, "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python",
                                                      "name": "python3"},
                                       "language_info": {"name": "python"}},
          "nbformat": 4, "nbformat_minor": 5}
    out = ROOT / "kaggle" / name
    out.parent.mkdir(exist_ok=True)
    out.write_text(json.dumps(nb, indent=1), encoding="utf-8")
    print(f"wrote {out} ({len(cells)} cells)")


if __name__ == "__main__":
    main()
